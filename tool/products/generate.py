#!/usr/bin/env python3
"""Generate Dart registry and Gradle data from validated product manifests."""
import argparse
import json
import shutil
import subprocess
import tempfile
from registry import ROOT, load_registry


def literal(value):
    if isinstance(value, str):
        return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"
    if isinstance(value, list): return '[' + ', '.join(literal(v) for v in value) + ']'
    return json.dumps(value)


def camel(name):
    first, *rest = name.split('_')
    return first + ''.join(p.title() for p in rest)


def generated_files():
    products = load_registry()
    lines = ["// Generated by tool/products/generate.py; do not edit.", "import 'package:flutter/material.dart';", "import 'product_configuration.dart';", '', 'const productRegistry = <String, ProductConfiguration>{']
    android = []
    for p in products.values():
        if not p.ready:
            continue
        d = p.data; i = d['identity']; a = d['appearance']; c = d['content']
        fields = dict(id=p.id, name=i['name'], displayNameFa=i['display_name_fa'], applicationId=p.application_id, versionName=p.version_name, versionCode=p.version_code, storageScope=i['storage_scope'], icon=i['icon'].removeprefix('apps/game/'),fontFamily=a['font_family'],homeLayout=a['home_layout'],defaultStyle=a['default_style'],largeControls=a['large_controls'],navigation=a['navigation'],offlineManifest=c['offline_manifest'].removeprefix('apps/game/'),onlineRoot=c['online_root'],onlineManifest=c['online_manifest'],categories=c['categories'],defaultCategories=c['default_categories'],maxDimension=c['max_dimension'])
        lines.append(f'  {literal(p.id)}: ProductConfiguration(')
        for k,v in fields.items():
            lines.append(f'    {k}: {literal(v)},')
        for key in ('primary','secondary','background'):
            lines.append(f'    {key}: Color(0xff{a[key][1:]}),')
        lines.append(f'    themeMode: ThemeMode.{a["theme_mode"]},')
        lines.append('    features: ProductFeatures(')
        for k,v in d['features'].items():
            if k not in ('free_painting','background_music'):
                lines.append(f'      {camel(k)}: {json.dumps(v)},')
        lines.extend(['    ),','  ),'])
        android.append(dict(id=p.id, applicationId=p.application_id, name=i['name'], versionName=p.version_name,versionCode=p.version_code,signingPrefix=p.signing_prefix,icon=i['icon'].removeprefix('apps/game/'),background=a['background'],primary=a['primary']))
    lines.append('};')
    dart_source='\n'.join(lines)+'\n'
    if shutil.which('dart'):
        with tempfile.TemporaryDirectory() as tmp:
            path=__import__('pathlib').Path(tmp)/'products.dart';path.write_text(dart_source)
            subprocess.run(['dart','format',str(path)],check=True,stdout=subprocess.DEVNULL)
            dart_source=path.read_text()
    return {'apps/game/lib/products/products.g.dart':dart_source,'products/android-products.json':json.dumps(android,indent=2)+'\n'}


def generate(check=False):
    for path, content in generated_files().items():
        target=ROOT/path
        if check:
            if not target.exists() or target.read_text()!=content:
                raise SystemExit(f'{path} is stale: run python3 tool/products/generate.py')
        else:
            target.parent.mkdir(parents=True,exist_ok=True)
            target.write_text(content)

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
