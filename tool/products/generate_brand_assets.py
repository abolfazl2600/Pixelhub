#!/usr/bin/env python3
"""Render the two simple vector product marks; never modify the original mark.

Development-only dependency: Pillow. Platform sizes are generated by Dart.
"""
from pathlib import Path
from PIL import Image, ImageDraw
root=Path(__file__).resolve().parents[2]/'apps/game/assets/brand'
for product, background in [('kids','#7856C8'),('art','#825735')]:
    image=Image.new('RGB',(512,512),background)
    draw=ImageDraw.Draw(image)
    if product=='kids':
        # Four building blocks form a friendly colorful pinwheel.
        for box,color in [((76,76,244,244),'#FFE17A'),((268,76,436,244),'#77DCDA'),((76,268,244,436),'#FFA6C9'),((268,268,436,436),'#ADDE75')]:
            draw.rounded_rectangle(box,radius=42,fill=color)
        draw.ellipse((214,214,298,298),fill='#FFFFFF')
    else:
        # A framed canvas and brush distinguish the fine-art edition.
        draw.rounded_rectangle((70,70,442,442),radius=24,fill='#F2B957')
        draw.rectangle((96,96,416,416),fill='#FFF9EF')
        draw.polygon([(120,370),(230,170),(382,370)],fill='#7A9A8A')
        draw.ellipse((294,126,366,198),fill='#D99B49')
        draw.line((164,358,350,172),fill='#825735',width=30)
    image.save(root/f'{product}_mark.png',optimize=True)
